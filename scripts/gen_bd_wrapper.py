# gen_bd_wrapper.py - generate ip/<ip>/rtl/<ip>_bd.v, the Verilog wrapper of an
# omac IP for a Vivado IP integrator block design (module reference needs a
# Verilog top), from the SystemVerilog top's parameter and port list. Adds
# interface attributes to clk, rst, gt_rx_clk (when it is a single clock) and the
# two AXI-Streams.
# Usage: gen_bd_wrapper.py [ip ...] [--check]   (default: omac_10g omac_40g)
#   --check: exit 1 if the checked-in wrapper differs from what would be generated
#
# Copyright (c) 2026 Opsero Electronic Design Inc.

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def gen(ip):
    src = open(os.path.join(ROOT, 'ip', ip, 'rtl', ip + '.sv')).read()
    head, rest = src.split(') (', 1)
    body = rest.split(');', 1)[0]
    params = re.findall(r'parameter\s+(?:int|bit|logic\s*\[[^\]]+\])\s+(\w+)\s*=\s*(.+?)\s*,?\s*(?://.*)?$',
                        head, re.M)
    ports = re.findall(r'(input|output)\s+(?:wire\s+)?logic\s*(\[[^\]]+\])?\s*(\w+)', body)
    iface = {
        'clk': ['xilinx.com:signal:clock:1.0 clk CLK',
                'ASSOCIATED_BUSIF s_axis_tx:m_axis_rx, ASSOCIATED_RESET rst'],
        'rst': ['xilinx.com:signal:reset:1.0 rst RST', 'POLARITY ACTIVE_HIGH'],
        'gt_rx_clk': ['xilinx.com:signal:clock:1.0 gt_rx_clk CLK', None],
    }
    for bus in ('s_axis_tx', 'm_axis_rx'):
        for sig in ('tdata', 'tkeep', 'tvalid', 'tready', 'tlast', 'tuser'):
            iface['%s_%s' % (bus, sig)] = ['xilinx.com:interface:axis:1.0 %s %s' % (bus, sig.upper()), None]
    plines = []
    for n, v in params:
        if v == "'1":
            v = "{58{1'b1}}"
        plines.append('    parameter %s = %s' % (n, v))
    lines = []
    for d, w, n in ports:
        a = ''
        if n in iface and not (n == 'gt_rx_clk' and w):
            info, par = iface[n]
            a = '    (* X_INTERFACE_INFO = "%s" *)\n' % info
            if par:
                a += '    (* X_INTERFACE_PARAMETER = "%s" *)\n' % par
        lines.append('%s    %s wire %s%s' % (a, d, (w + ' ') if w else '', n))
    pconn = ',\n'.join('        .%s(%s)' % (n, n) for n, _ in params)
    conn = ',\n'.join('        .%s(%s)' % (n, n) for _, _, n in ports)
    return ('''// SPDX-License-Identifier: MIT
//
// %(ip)s_bd - Verilog wrapper of %(ip)s for a Vivado IP integrator block design
// (module reference needs a Verilog top). GENERATED by scripts/gen_bd_wrapper.py
// from %(ip)s.sv: same parameters and ports; the clocks, the reset and the
// AXI-Streams carry interface attributes. Do not edit; regenerate.
//
// Copyright (c) 2026 Opsero Electronic Design Inc.

`timescale 1ns / 1ps

module %(ip)s_bd #(
%(p)s
) (
%(l)s
);

%(ip)s #(
%(pc)s
) u_%(ip)s (
%(c)s
);

endmodule
''' % dict(ip=ip, p=',\n'.join(plines), l=',\n'.join(lines), pc=pconn, c=conn))


def main():
    args = sys.argv[1:]
    check = '--check' in args
    ips = [a for a in args if a != '--check'] or ['omac_10g', 'omac_40g']
    bad = 0
    for ip in ips:
        path = os.path.join(ROOT, 'ip', ip, 'rtl', ip + '_bd.v')
        txt = gen(ip)
        if check:
            same = os.path.exists(path) and open(path).read() == txt
            print('%s: %s' % (path, 'up to date' if same else 'OUT OF DATE'))
            bad += 0 if same else 1
        else:
            open(path, 'w').write(txt)
            print('wrote', path)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
